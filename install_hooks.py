# -*- coding: utf-8 -*-
"""把桌宠的 hook 写进 Claude Code 的设置里。

原理：Claude Code 每做一件事都会触发一个 hook，我们让它调一个小脚本，脚本用 curl
把事件原样转给桌宠开的本地端口。curl 是 Windows 10 自带的，不用另外装。

一共装三样：
1. 状态类 hook（15 个事件）：在后台跑，不拖慢 Claude Code。
2. 审批 hook（PermissionRequest）：要你点"允许"的时候把请求交给桌宠，你在桌宠上点了
   就直接生效；桌宠没开、或者你一直没理，就什么都不回，照常在窗口里问你。
3. 状态栏（命令行版才有）：底部那一行，顺便把官方额度数字转给桌宠。
   你已经有自己的状态栏的话，不会动它。

用法：
    python install_hooks.py                 装到用户级设置（所有项目都生效）
    python install_hooks.py --project       只装到当前项目的 .claude/settings.json
    python install_hooks.py --remove        卸载
    python install_hooks.py --show          只打印要写入的内容，不动文件
    python install_hooks.py --port 5000     换端口
    python install_hooks.py --no-approve    不装审批 hook
    python install_hooks.py --no-statusline 不装状态栏
"""

import argparse
import json
import os
import shutil
import sys
import time

MARKER = "claude-pet"
DEFAULT_PORT = 47828
ASK_WAIT_S = 600        # 审批 hook 最多挂多久；真正等多久看桌宠菜单里"审批卡片最多等"

# 状态类事件：全部原样转给桌宠，由桌宠自己分辨是哪个会话、在干什么
ASYNC_EVENTS = [
    "SessionStart", "SessionEnd", "UserPromptSubmit",
    "PreToolUse", "PostToolUse", "PostToolUseFailure",
    "Notification", "SubagentStart", "SubagentStop",
    "PreCompact", "PostCompact", "Stop", "StopFailure",
    "TaskCreated", "TaskCompleted",
]

APP_DIR = os.path.dirname(os.path.abspath(__file__))

# Windows 控制台有时不是 UTF-8，先掰正，免得中文报错
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass


def is_windows():
    return sys.platform.startswith("win")


def script(stem):
    return os.path.join(APP_DIR, stem + (".cmd" if is_windows() else ".sh"))


def async_hook(event, port):
    """拆成 "cmd /c call 脚本 参数" 这种全是普通词的形式最稳，不用操心引号。
    脚本自己永远返回 0，所以桌宠没开的时候 Claude Code 不会报错。"""
    extra = ["wake"] if event == "SessionStart" else []
    if is_windows():
        args = ["/c", "call", script("claude-pet-notify"), "hook", str(port)] + extra
        return {"type": "command", "command": "cmd", "args": args, "timeout": 5, "async": True}
    args = [script("claude-pet-notify"), "hook", str(port)] + extra
    return {"type": "command", "command": "bash", "args": args, "timeout": 5, "async": True}


def ask_hook(port):
    if is_windows():
        args = ["/c", "call", script("claude-pet-ask"), str(port), str(ASK_WAIT_S)]
        cmd = "cmd"
    else:
        args = [script("claude-pet-ask"), str(port), str(ASK_WAIT_S)]
        cmd = "bash"
    return {"type": "command", "command": cmd, "args": args, "timeout": ASK_WAIT_S + 15,
            "onFailure": "continue"}


def build_hooks(port, approve=True):
    hooks = {}
    for event in ASYNC_EVENTS:
        hooks[event] = [{"hooks": [async_hook(event, port)]}]
    if approve:
        hooks["PermissionRequest"] = [{"hooks": [ask_hook(port)]}]
    return hooks


def statusline_entry(port):
    path = os.path.join(APP_DIR, "claude-pet-statusline.py").replace("\\", "/")
    if shutil.which("python"):
        cmd = f'python "{path}"'
    else:
        cmd = f'"{sys.executable.replace(chr(92), "/")}" "{path}"'
    if port != DEFAULT_PORT:
        cmd += f" {port}"
    return {"type": "command", "command": cmd, "padding": 0}


def write_wake_script():
    """开新会话时桌宠没开，就用它在后台把桌宠叫起来。"""
    if not is_windows():
        return None
    pyw = sys.executable
    if pyw.lower().endswith("python.exe"):
        pyw = pyw[:-len("python.exe")] + "pythonw.exe"
    main = os.path.join(APP_DIR, "main.py")
    path = os.path.join(APP_DIR, "wake.vbs")
    content = (
        "' claude-pet: start the pet in the background (generated by install_hooks.py)\r\n"
        'Set sh = CreateObject("WScript.Shell")\r\n'
        f'sh.CurrentDirectory = "{APP_DIR}"\r\n'
        f'sh.Run """{pyw}"" ""{main}""", 0, False\r\n'
    )
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(content)
    return path


def settings_path(project):
    if project:
        return os.path.join(os.getcwd(), ".claude", "settings.json")
    home = os.environ.get("CLAUDE_CONFIG_DIR") or os.path.join(os.path.expanduser("~"), ".claude")
    return os.path.join(home, "settings.json")


def load_settings(path):
    if not os.path.exists(path):
        return {}
    try:
        with open(path, "r", encoding="utf-8") as fh:
            text = fh.read().strip()
        return json.loads(text) if text else {}
    except Exception as err:
        print(f"读不了现有设置 {path}：{err}")
        print("为了不弄坏你的配置，这里先停下。请手动检查这个文件。")
        sys.exit(1)


def strip_ours(hooks):
    """把之前装过的桌宠 hook 清掉，别重复堆积。你自己的 hook 一条都不动。"""
    cleaned = {}
    for event, groups in (hooks or {}).items():
        kept = []
        for group in groups:
            inner = [h for h in group.get("hooks", []) if MARKER not in json.dumps(h)]
            if inner:
                new_group = dict(group)
                new_group["hooks"] = inner
                kept.append(new_group)
        if kept:
            cleaned[event] = kept
    return cleaned


def merge(existing, ours):
    merged = dict(existing)
    for event, groups in ours.items():
        merged.setdefault(event, [])
        merged[event] = merged[event] + groups
    return merged


def write_settings(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if os.path.exists(path):
        backup = f"{path}.bak-{time.strftime('%Y%m%d-%H%M%S')}"
        shutil.copy2(path, backup)
        print(f"旧设置已备份到：{backup}")
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    print(f"写好了：{path}")


def main():
    parser = argparse.ArgumentParser(description="给 Claude Code 装桌宠 hook")
    parser.add_argument("--port", type=int, default=DEFAULT_PORT)
    parser.add_argument("--project", action="store_true", help="只装到当前项目")
    parser.add_argument("--remove", action="store_true", help="卸载")
    parser.add_argument("--show", action="store_true", help="只看内容，不写文件")
    parser.add_argument("--no-approve", action="store_true", help="不装审批 hook")
    parser.add_argument("--no-statusline", action="store_true", help="不装状态栏")
    args = parser.parse_args()

    path = settings_path(args.project)
    ours = build_hooks(args.port, approve=not args.no_approve)

    if not args.remove:
        for stem in ("claude-pet-notify", "claude-pet-ask"):
            if not os.path.exists(script(stem)):
                print(f"找不到脚本：{script(stem)}")
                print("请确认 install_hooks.py 和它在同一个文件夹里。")
                sys.exit(1)
            if not is_windows():
                try:
                    os.chmod(script(stem), 0o755)
                except Exception:
                    pass
        if shutil.which("curl") is None:
            print("警告：系统里没找到 curl，hook 会调不通。")
            print("Windows 10 1803 以后自带 curl，太老的系统需要自己装一个。")

    if args.show:
        print(json.dumps({"hooks": ours, "statusLine": statusline_entry(args.port)}, ensure_ascii=False, indent=2))
        return

    data = load_settings(path)
    data["hooks"] = strip_ours(data.get("hooks", {}))
    ours_statusline = MARKER in json.dumps(data.get("statusLine") or {})

    if args.remove:
        if not data["hooks"]:
            data.pop("hooks", None)
        if ours_statusline:
            data.pop("statusLine", None)
        write_settings(path, data)
        print("桌宠的 hook 已经拆掉了。")
        return

    data["hooks"] = merge(data["hooks"], ours)
    statusline_note = ""
    if not args.no_statusline:
        if "statusLine" not in data or ours_statusline:
            data["statusLine"] = statusline_entry(args.port)
            statusline_note = "状态栏也装上了（命令行版 Claude Code 底部那一行）。"
        else:
            statusline_note = "你已经有自己的状态栏了，没动它。"
    elif ours_statusline:
        data.pop("statusLine", None)
    write_settings(path, data)
    wake = write_wake_script()

    count = sum(len(v) for v in ours.values())
    print(f"装了 {count} 条 hook，端口 {args.port}。")
    if statusline_note:
        print(statusline_note)
    if wake:
        print(f"开新会话时桌宠没开会自动叫醒她（{os.path.basename(wake)}），不想要就在右键菜单里关掉。")
    print("下一步：")
    print("  1. 先把桌宠跑起来（双击 run.bat）。")
    print("  2. Claude Code 会自己读到新的 hook，不用重开会话；随便让它做点事，看她会不会换表情。")
    print("  3. 想确认桌宠在听：浏览器打开 http://127.0.0.1:%d/ping" % args.port)


if __name__ == "__main__":
    main()
